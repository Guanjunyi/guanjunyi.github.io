/* =========================================================
   Automatically generate publication list
   ========================================================= */

const publicationContainer =
  document.getElementById("publication-list");


/* =========================================================
   Separate published papers and preprints
   ========================================================= */

const regularPublications =
  publications.filter(pub => typeof pub.year === "number");


const preprintPublications =
  publications.filter(pub => typeof pub.year !== "number");


/* =========================================================
   Sort published papers by year
   ========================================================= */

regularPublications.sort((a, b) => b.year - a.year);


/* =========================================================
   Group by year
   ========================================================= */

const groupedPublications = {};


regularPublications.forEach(pub => {

  if (!groupedPublications[pub.year]) {
    groupedPublications[pub.year] = [];
  }

  groupedPublications[pub.year].push(pub);

});



/* =========================================================
   Render one publication
   ========================================================= */

function renderPublication(pub) {


  let titleHTML = pub.title;


  if (pub.paper) {

    titleHTML = `

      <a
        href="${pub.paper}"
        target="_blank"
        rel="noopener noreferrer"
      >
        ${pub.title}
      </a>

    `;

  }



  let linksHTML = "";


  if (pub.paper) {

    linksHTML += `

      <a
        href="${pub.paper}"
        target="_blank"
        rel="noopener noreferrer"
      >
        [Paper]
      </a>

    `;

  }


  if (pub.code) {

    linksHTML += `

      <a
        href="${pub.code}"
        target="_blank"
        rel="noopener noreferrer"
      >
        [Code]
      </a>

    `;

  }



  return `

    <div class="publication">

      <div class="pub-title">

        ${titleHTML}

      </div>


      <div class="authors">

        ${pub.authors}

      </div>


      <div class="venue">

        ${pub.venue}

      </div>


      <div class="pub-links">

        ${linksHTML}

      </div>

    </div>

  `;

}



/* =========================================================
   Render published papers
   ========================================================= */

Object.keys(groupedPublications)

  .sort((a, b) => Number(b) - Number(a))

  .forEach(year => {


    publicationContainer.innerHTML += `

      <h3>
        ${year}
      </h3>

    `;


    groupedPublications[year].forEach(pub => {

      publicationContainer.innerHTML +=
        renderPublication(pub);

    });


  });



/* =========================================================
   Render preprints
   ========================================================= */

if (preprintPublications.length > 0) {


  publicationContainer.innerHTML += `

    <h3>
      Preprints / Early Access
    </h3>

  `;


  preprintPublications.forEach(pub => {

    publicationContainer.innerHTML +=
      renderPublication(pub);

  });


}
